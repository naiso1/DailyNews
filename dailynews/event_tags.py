"""Edition-independent event tags; publication and browser use the same rules.

An explicit event year takes precedence over the article date. Unqualified
event names are assigned to 2026 only for articles dated in 2026. Ideas, stored
genre tags, and the current clock are never evidence for an event.
"""
import json
from pathlib import Path
import re
import unicodedata
from urllib.parse import unquote

from dailynews.article_text import NOISE_BOUNDARIES, trim_article_noise

RULES = [
    {"tag": "CEATEC×JMS2026", "year": "2026", "pattern": r"(?<![a-z])CEATEC(?![a-z])|シーテック|(?<![a-z])Japan[\s_-]+Mobility[\s_-]+Show(?:[\s_-]+Bizweek)?(?![a-z])|ジャパン[\s・_-]*モビリティ[\s・_-]*ショー(?:[\s・_-]*ビズウィーク)?|(?<![a-z])JMS(?:[\s_-]*Bizweek)?(?![a-z])"},
    {"tag": "パリモーターショー2026", "year": "2026", "pattern": r"パリ[\s・_-]*(?:モーター[\s・_-]*ショー|オート[\s・_-]*ショー|自動車ショー)|(?<![a-z])Paris[\s_-]+(?:Motor|Auto|Automobile)[\s_-]+Show(?![a-z])|(?<![a-z])Mondial[\s_-]+(?:de[\s_-]+l['’\s_-]*|de[\s_-]+)(?:Automobile|Auto)(?![a-z])|巴黎(?:国际|國際)?(?:汽車|汽车|車|车)展"},
]
LABELS = [rule["tag"] for rule in RULES]
FIELDS = ("title", "desc", "summary", "sourceExcerpt", "sourceExcerptEnd", "originalTitle", "originalDesc", "url")
BEFORE = r"(?<!\d)(20\d{2})(?:\s*年[春夏秋冬]?(?:の|に開催された)?|[\s_-]+edition)?[\s:：・·/_()（）「」【】-]*$"
AFTER = r"^[\s:：・·/_()（）「」【】-]*(?:in\s+)?(20\d{2})(?!\d)"
PAST_BEFORE = r"(?:昨年|一昨年|昨秋|\d+\s*年前)(?:の)?\s*$"
PAST_AFTER = r"^\s*(?:\d+\s+years?\s+ago|last\s+year)(?![a-z])"


def derive(item):
    texts = [trim_article_noise(unicodedata.normalize("NFKC", unquote(str(item.get(field) or ""))), item.get("url")) for field in FIELDS]
    article_year = str(item.get("date") or "")[:4]
    result = []
    for rule in RULES:
        explicit, undated, past = [], False, False
        for text in texts:
            for match in re.finditer(rule["pattern"], text, re.I):
                before = re.search(BEFORE, text[max(0, match.start()-32):match.start()], re.I)
                after = re.search(AFTER, text[match.end():match.end()+32], re.I)
                years = [hit.group(1) for hit in (before, after) if hit]
                past |= bool(re.search(PAST_BEFORE, text[max(0, match.start()-32):match.start()], re.I) or
                             re.search(PAST_AFTER, text[match.end():match.end()+32], re.I))
                explicit.extend(years)
                undated |= not years
        # An old event mentioned alongside a 2026 vehicle is still an old event.
        if rule["year"] in explicit or (not explicit and not past and undated and article_year == rule["year"]):
            result.append(rule["tag"])
    return result


def browser_script():
    return '''"use strict";
// Generated by python -m dailynews.event_tags; edit the Python source.
(() => {
  const rules = ''' + json.dumps(RULES, ensure_ascii=False, indent=2) + ''';
  const fields = ''' + json.dumps(FIELDS) + ''';
  const noiseBoundaries = ''' + json.dumps(NOISE_BOUNDARIES, ensure_ascii=False) + ''';
  const before = new RegExp(''' + json.dumps(BEFORE) + ''', "i");
  const after = new RegExp(''' + json.dumps(AFTER) + ''', "i");
  const pastBefore = new RegExp(''' + json.dumps(PAST_BEFORE) + ''', "i");
  const pastAfter = new RegExp(''' + json.dumps(PAST_AFTER) + ''', "i");
  const labels = rules.map(rule => rule.tag);
  function derive(item) {
    let host = "";
    try { host = new URL(item?.url).hostname.toLowerCase().replace(/^www\\./, ""); } catch (_) { /* no source URL */ }
    const texts = fields.map(field => {
      let text = String(item?.[field] || "");
      try { text = decodeURIComponent(text); } catch (_) { /* literal URL */ }
      text = text.normalize("NFKC");
      const boundary = noiseBoundaries[host] && new RegExp(noiseBoundaries[host], "i").exec(text);
      return boundary ? text.slice(0, boundary.index).trimEnd() : text;
    });
    return rules.filter(rule => {
      const explicit = []; let undated = false, past = false;
      for (const text of texts) {
        for (const match of text.matchAll(new RegExp(rule.pattern, "ig"))) {
          const years = [before.exec(text.slice(Math.max(0, match.index-32), match.index)),
            after.exec(text.slice(match.index+match[0].length, match.index+match[0].length+32))]
            .filter(Boolean).map(hit => hit[1]);
          explicit.push(...years); if (!years.length) undated = true;
          past ||= pastBefore.test(text.slice(Math.max(0, match.index-32), match.index)) ||
            pastAfter.test(text.slice(match.index+match[0].length, match.index+match[0].length+32));
        }
      }
      return explicit.includes(rule.year) || (!explicit.length && !past && undated && String(item?.date || "").slice(0,4) === rule.year);
    }).map(rule => rule.tag);
  }
  // eventTags preserves classification from original source text at publication.
  const forItem = item => {
    const derived = derive(item);
    return labels.filter(tag => derived.includes(tag) || (item?.eventTags || []).includes(tag));
  };
  window.DailyNewsEventTags = {rules, labels, derive, forItem};
})();
'''


if __name__ == "__main__":
    path = Path(__file__).resolve().parents[1] / "dailynews_event_tags.js"
    path.write_text(browser_script(), encoding="utf-8")
    print(f"Generated {len(RULES)} event tags: {path.name}")
